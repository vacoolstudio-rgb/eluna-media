import 'dart:io';

import 'package:flutter/services.dart';

import '../domain/media_format.dart';

/// Раскодирует системой те картинки, которые FFmpeg читает не целиком.
///
/// Существует ради одного измеренного дефекта. Снимок с айфона — это HEIC, чья
/// картинка разрезана на плитки 512×512 и собирается элементом `grid`.
/// Встроенный FFmpeg этот grid разбирает и даже сообщает настоящий размер
/// (`Stream group #0:0: Tile Grid: hevc, 1024x768`), но сшивать плитки его
/// командный слой не умеет: и умолчание, и `-map 0:g:0`, и `-map 0:v` отдают
/// кодировщику ровно одну плитку. Снимок 4032×3024 превращался в свой левый
/// верхний угол — и конверсия при этом сообщала об успехе.
///
/// Сшить их можно и самим, фильтром `xstack` (проверено, работает), но для
/// этого нужно знать геометрию сетки, а итоговый размер кадра FFprobeKit в
/// структурированных данных не отдаёт — он есть только текстом в логе. Разбор
/// лога регуляркой ломается от версии к версии, а на снимке 4032×3024 плиток
/// уже 48. Системный декодер не знает ни одной из этих проблем: это тот же
/// код, которым снимок рисуется в «Фото», поэтому и плитка, и ориентация из
/// EXIF, и цветовое пространство обрабатываются правильно по определению.
///
/// Отказывает закрыто: любой сбой возвращает `null`, и конвейер работает с
/// исходным файлом ровно так, как работал до появления этого класса.
class StillDecoder {
  const StillDecoder({MethodChannel? channel})
      : _channel = channel ?? const MethodChannel('eluna/share_intake');

  final MethodChannel _channel;

  /// Расширения, которые FFmpeg этой сборки читает ненадёжно.
  ///
  /// Список намеренно короткий и по расширению, а не по содержимому: плиточным
  /// бывает любой HEIC, отличить его заранее можно только лишним прогоном
  /// FFprobe, а декодировать системой безобидно и для неплиточного. Прочие
  /// форматы сюда не попадают — у них проблемы нет, а лишний PNG на 30 МБ есть.
  static const _handled = {'heic', 'heif'};

  static bool handles(String path) {
    final dot = path.lastIndexOf('.');
    if (dot < 0) return false;
    return _handled.contains(path.substring(dot + 1).toLowerCase());
  }

  /// Путь к полноразмерному PNG рядом с исходником, или `null`, если платформа
  /// не смогла — включая все платформы, где этого канала нет.
  ///
  /// Удалять результат — забота вызывающего: файл большой и живёт ровно
  /// столько, сколько идёт одна конверсия.
  Future<String?> decode(String path) async {
    if (!handles(path)) return null;
    if (!File(path).existsSync()) return null;

    // Рядом с исходником, а не в общей папке: исходник уже лежит в кэше,
    // который очередь считает расходным, и второй временный файл там же
    // исчезнет вместе с ним, даже если процесс умрёт до уборки.
    final outputPath = '$path.decoded.png';
    try {
      final ok = await _channel.invokeMethod<bool>('decodeStill', {
        'path': path,
        'outputPath': outputPath,
      });
      if (ok != true) return null;
    } on PlatformException {
      return null;
    } on MissingPluginException {
      // Хост-тесты, десктоп, и Android до тех пор, пока свою половину канала
      // там не напишут: канала нет — декодировать нечем.
      return null;
    }

    // Платформа сказала «получилось» — но файла может не быть, если её ответ
    // разошёлся с диском. Пустой PNG уронил бы конверсию вместо того, чтобы
    // тихо отступить.
    final file = File(outputPath);
    if (!file.existsSync() || file.lengthSync() == 0) {
      if (file.existsSync()) file.deleteSync();
      return null;
    }
    return outputPath;
  }

  /// Правда ли этот исходник стоит прогонять через систему.
  ///
  /// Отдельно от [handles], потому что вопрос другой: у видео своего дефекта
  /// нет, а `.heic` в списке кадров склейки — это всё ещё картинка.
  static bool worthDecoding(String path) =>
      handles(path) && ContainerFormat.kindOfFile(path) == MediaKind.image;
}
