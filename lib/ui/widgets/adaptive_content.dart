import 'package:flutter/material.dart';

/// Центрирует содержимое и не даёт ему растянуться шире, чем читается.
///
/// На телефоне не делает ничего: предел заведомо больше экрана, и
/// `ConstrainedBox` просто пропускает ширину дальше. Всё поведение начинается
/// на планшете, ради которого класс и появился, — поэтому размерный класс тут
/// не спрашивается: у формы одна удобная ширина, а не три.
///
/// Зачем вообще: строка текста шириной в тринадцатидюймовый экран нечитаема, а
/// форма, растянутая на тысячу точек, перестаёт быть формой — подпись уезжает
/// от своего поля на полметра. Предел ширины берётся из общего пакета, а не
/// придумывается здесь, чтобы три приложения семьи держали одну колонку.
///
/// Ставится как можно **ближе к содержимому**, а не вокруг `Scaffold`: фон,
/// разделители и полосы прокрутки должны оставаться во всю ширину, иначе на
/// планшете появляется впечатление окна внутри окна.
class AdaptiveContent extends StatelessWidget {
  const AdaptiveContent({super.key, required this.child, this.maxWidth});

  /// Предел для экранов-форм, и он **уже** семейного [ShellMetrics.contentMaxWidth].
  ///
  /// Тот предел описан как «колонка ленты» — им меряют список карточек, где
  /// широкая строка нормальна. Здесь же вкладки это форма: подпись, её поле и
  /// сразу вторая пара рядом. У ленты от лишней ширины страдает только
  /// читаемость, у формы — связь подписи с полем, и страдает раньше.
  ///
  /// 840 выбрано не на глаз: при нём двухколоночные карточки пресетов выходят
  /// примерно той же ширины, что на телефоне, то есть перестают растягиваться,
  /// а не просто становятся длиннее. Семейное значение (1040) на
  /// тринадцатидюймовом планшете в портрете шире, чем остаётся места после
  /// рейки, поэтому не срабатывало вовсе.
  static const formMaxWidth = 840.0;

  final Widget child;

  /// Переопределение предела. Нужно там, где колонка по смыслу уже, — например
  /// у экрана-приветствия, который читается как абзац, а не как форма.
  final double? maxWidth;

  @override
  Widget build(BuildContext context) {
    final limit = maxWidth ?? formMaxWidth;
    return Align(
      alignment: Alignment.topCenter,
      child: ConstrainedBox(
        constraints: BoxConstraints(maxWidth: limit),
        child: child,
      ),
    );
  }
}
